"""Generate PROMPTS.md from the real sources. Never hand-edit PROMPTS.md.

Transparency about a benchmark means publishing the exact text the model is
given. A hand-written copy drifts: on 2026-08-31 the `fib` smoke prompt was
changed and two test doubles still matched the old wording, so the only safe
version of this document is one derived from `tasks.toml` and `smoke.py`
themselves.

    uv run python gen_prompts.py > PROMPTS.md
"""

from __future__ import annotations

import pathlib
import tomllib

import smoke

HERE = pathlib.Path(__file__).parent


def main() -> None:
    cfg = tomllib.loads((HERE / "tasks.toml").read_text())
    out: list[str] = []
    add = out.append

    add("# Every prompt this benchmark sends")
    add("")
    add("**Generated by `gen_prompts.py`. Do not hand-edit — regenerate.**")
    add("")
    add(
        "Two kinds of prompt reach a model here: the **agent tasks**, which are the "
        "measurement, and the **smoke probes**, which decide whether a backend is "
        "healthy enough to measure. Both are below verbatim."
    )
    add("")
    add("## What else the model receives")
    add("")
    add(
        "The prompt below is the *only* text this harness composes. Everything else "
        "in the model's context is put there by the client — its own system prompt, "
        "tool definitions, and whatever it reads from the repository. Those differ "
        "per client and per version, which is one reason the same model scores "
        "differently under Claude Code, Aider and OpenCode."
    )
    add("")
    add(
        "The agent is given a checkout in which one function body has been replaced "
        "by `NotImplementedError`, and the repository's own test suite is the sole "
        "oracle. No test is shown to the model as a target, and modifying tests is "
        "forbidden by the prompt and checked afterwards (`touched_tests`)."
    )
    add("")

    add("## Agent tasks")
    add("")
    add(
        f"`{cfg['repo']}` pinned at `{cfg['base_commit']}` unless a task names its own."
    )
    add("")
    for task in cfg["task"]:
        add(f"### `{task['name']}`")
        add("")
        meta = []
        if task.get("repo"):
            meta.append(f"repo `{task['repo']}`")
        if task.get("base_commit"):
            meta.append(f"@ `{task['base_commit']}`")
        if task.get("test_command"):
            meta.append(f"oracle `{task['test_command']}`")
        if task.get("keep_docstring") is not None:
            meta.append(f"keep_docstring `{task['keep_docstring']}`")
        if meta:
            add(" · ".join(meta))
            add("")
        add("```text")
        add(task["prompt"].strip())
        add("```")
        add("")

    add("## Smoke probes")
    add("")
    add(
        f'Sent to `/v1/messages` with `thinking: {{"type": "adaptive"}}`, '
        f"`temperature 0`, `max_tokens {smoke.MAX_TOKENS}`, deadline "
        f"{smoke.DEADLINE_SECONDS}s. The reply is **executed** against the assertion; "
        "the gate refuses a wrong answer that arrived in time and warns about a slow one."
    )
    add("")
    add(
        "**Every probe states its whole specification.** A probe that can fail for "
        "want of world knowledge cannot tell a degraded backend from an ignorant "
        "one — see the `fib` note in `smoke.py`."
    )
    add("")
    for name, prompt, assertion in smoke.SMOKE_TASKS:
        add(f"### `{name}`")
        add("")
        add("```text")
        add(prompt)
        add("```")
        add("")
        add("Checked with:")
        add("")
        add("```python")
        add(assertion)
        add("```")
        add("")

    print("\n".join(out).rstrip() + "\n")


if __name__ == "__main__":
    main()
