def test_write_shim_records_argv_and_env_through_child_run(tmp_path) -> None:
    """The shim works, and `child.run`'s unset reaches the recorded child.

    The host exports an operator's leftover of the #149 variable; the reference
    arm must strip it anyway, and the fake proves it by recording the child's
    env without the key. This is the mechanism assertion 2 rests on.
    """
    out = tmp_path / "rec.jsonl"
    shim = equiv.write_shim(tmp_path / "shim", out)
    for arm in ("t", "r"):
        if arm == "t":
            equiv.run_fake(
                shim,
                "ds4-server",
                arm,
                ["--port", "8000"],
                {equiv.TENSOR_ENV: "1"},
                (),
                out,
                tmp_path / "spawn.log",
                via="ds4-server",
            )
        else:
            equiv.run_fake(
                shim,
                "ds4-server",
                arm,
                ["--port", "8000"],
                {},
                (equiv.TENSOR_ENV,),
                out,
                tmp_path / "spawn.log",
                via="ds4-server",
            )
    recs = equiv.by_program(equiv.load(out), "ds4-server")
    assert len(recs) == 2
    assert equiv.env_key_state(recs[0].env, equiv.TENSOR_ENV) == "set:1"
    assert equiv.env_key_state(recs[1].env, equiv.TENSOR_ENV) == "absent"


def test_uv_fake_default_executes_nothing(tmp_path) -> None:
    """Fail-closed: with no run_real, an unlisted script is recorded, not run.

    The default `run_real=()` is the safe state. A script that would be loud if
    it ran -- one that writes a marker file -- must be recorded and exited 0,
    with the marker never appearing. This is the guard that a differential
    which forgets to name its helpers gets a recorded no-op, not a real server.
    """
    import os
    import subprocess

    out = tmp_path / "rec.jsonl"
    uv = equiv.write_uv_fake_running_real(tmp_path / "uv", out, ROOT)
    marker = tmp_path / "loud-ran"
    loud = tmp_path / "loud.py"
    loud.write_text(
        f"#!/usr/bin/env python3\nopen({str(marker)!r}, 'w').write('ran')\n"
    )
    env = {
        "EQUIV_OUT": str(out),
        "EQUIV_ARM": "shell",
        "PATH": os.environ.get("PATH", ""),
    }
    got = subprocess.run(
        [sys.executable, str(uv), "run", "python", str(loud)],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert got.returncode == 0, got.stderr
    assert not marker.exists(), "the unlisted script ran for real"
    recs = equiv.load(out)
    assert len(recs) == 1
    assert recs[0].program == "loud.py"


def test_inline_c_executes_for_real_not_recorded(tmp_path) -> None:
    """`uv run python -c '<code>'` runs the code, because it is the shell's own
    source text inlined, not an external program.

    `ds4_record_route` and `worktree_code_dirty` invoke it. A fake that records
    `-c` and exits 0 would give the shell nothing while the port runs the same
    logic in-process -- an asymmetry that manufactures differences. The code
    must run for real, and the invocation must still be recorded.
    """
    import os
    import subprocess

    out = tmp_path / "rec.jsonl"
    uv = equiv.write_uv_fake_running_real(tmp_path / "uv", out, ROOT)
    marker = tmp_path / "c-ran"
    code = f"open({str(marker)!r}, 'w').write('ran')"
    env = {
        "EQUIV_OUT": str(out),
        "EQUIV_ARM": "shell",
        "PATH": os.environ.get("PATH", ""),
    }
    got = subprocess.run(
        [sys.executable, str(uv), "run", "python", "-c", code],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert got.returncode == 0, got.stderr
    assert marker.exists(), "the inline code did not run for real"
    recs = equiv.load(out)
    assert len(recs) == 1
    assert recs[0].program == "-c"


def test_fake_shim_emits_the_real_on_line_and_the_off_assumption(tmp_path) -> None:
    """The shim's ON line is the engine's; the OFF line is a stated assumption.

    The ON arm's startup line is read from the real-run excerpt
    `shim-strip-on.log`, so the fake prints exactly what the shim printed. The
    OFF line has no real example in the repo, so the fake emits the driver's
    own grep target and the README records the assumption. Both arms must reach
    the driver's `grep -q "$want"` check.
    """
    import os
    import subprocess

    out = tmp_path / "rec.jsonl"
    uv = equiv.write_uv_fake_running_real(tmp_path / "uv", out, ROOT, shim=True)
    base = {
        "EQUIV_OUT": str(out),
        "EQUIV_ARM": "shell",
        "PATH": os.environ.get("PATH", ""),
    }
    on = subprocess.run(
        [sys.executable, str(uv), "run", "python", "ds4_qwen_tool_shim.py"],
        env=base,
        capture_output=True,
        text=True,
        check=False,
    )
    assert on.returncode == 0, on.stderr
    # Read from the fixture, not retyped. A constant typed here would agree
    # with a fake that was typed from the same memory, which is exactly how
    # the OFF line stayed wrong for months.
    assert mode_line("shim-strip-on.log") in on.stdout
    off_env = dict(base, SHIM_NO_STRIP="1")
    off = subprocess.run(
        [sys.executable, str(uv), "run", "python", "ds4_qwen_tool_shim.py"],
        env=off_env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert off.returncode == 0, off.stderr
    # The WHOLE line, not the prefix. Until 2026-09-09 the fake printed a bare
    # `scaffolding strip: OFF` -- a line the shim has never produced -- and
    # this assertion passed on it, because `scaffolding strip: OFF` is a
    # substring of the real `scaffolding strip: OFF (experiment arm)
    # (#112 remedy 2)`. So did `strip_toggle_ab.sh:156`, which greps with
    # `grep -q "$want"`. Two substring matchers agreeing with each other is
    # not evidence about the shim.
    want = mode_line("shim-strip-off.log")
    assert "(experiment arm)" in want, "the OFF fixture lost its real text"
    assert want in off.stdout, f"want {want!r}, got {off.stdout!r}"


def mode_line(fixture: str) -> str:
    """The shim's `scaffolding strip: ...` line, out of a real-run excerpt.

    One owner for the text. The fake reads these same two files, so a fixture
    that loses its real wording fails here rather than quietly making the
    differential agree with itself.
    """
    path = ROOT / "tests" / "fixtures" / "logs" / fixture
    for raw in path.read_text().splitlines():
        if "scaffolding strip:" in raw:
            return raw.split("INFO ", 1)[-1].strip()
    raise AssertionError(f"{fixture} carries no strip line")


def test_fake_ds4_server_emits_the_real_graph_excerpt(tmp_path) -> None:
    """The fake's graph line is the engine's, not a hand-typed string.

    The heavy drivers grep the server log for `Qwen graph allocated` and
    `MTP=off` / `MTP=Q4_K/Q8_0/BF16` before they will run a measurement. The
    fake must emit those markers so the real `.sh` reaches the argv-construction
    point offline -- but the line must come from the real-run excerpt under
    `tests/fixtures/logs/`, never be composed here. This runs the fake both
    ways and asserts its stdout carries the markers the drivers grep for.
    """
    import os
    import subprocess

    out = tmp_path / "rec.jsonl"
    tree = tmp_path / "tree"
    fake = equiv.write_fake_ds4_server(tree, out, ROOT)
    env = {
        "EQUIV_OUT": str(out),
        "EQUIV_ARM": "shell",
        "PATH": os.environ.get("PATH", ""),
    }
    mtp = subprocess.run(
        [sys.executable, str(fake), "--mtp-model", "m.gguf"],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert mtp.returncode == 0, mtp.stderr
    assert "Qwen graph allocated" in mtp.stdout
    assert "MTP=Q4_K/Q8_0/BF16" in mtp.stdout
    assert "MTP sidecar loaded" in mtp.stdout
    plain = subprocess.run(
        [sys.executable, str(fake)],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert plain.returncode == 0, plain.stderr
    assert "Qwen graph allocated" in plain.stdout
    assert "MTP=off" in plain.stdout
    assert "MTP sidecar loaded" not in plain.stdout
    # both arms recorded their argv+env
    recs = equiv.by_program(equiv.load(out), "ds4-server")
    assert len(recs) == 2
    assert recs[0].argv == ("--mtp-model", "m.gguf")


def test_no_fixture_carries_env_outside_the_controlled_base() -> None:
    """A committed fixture must not record the operator's whole environment.

    The recording fakes capture `os.environ` wholesale. That is fine for a
    tmp-scoped capture, but a committed fixture that carried `LC_CTYPE` or a
    token would be a secret in the repo -- and gitleaks only catches keys that
    look like tokens. This asserts every env key in every fixture is one the
    driver set or the harness controls.
    """
    leaks = []
    for path in sorted(FIXTURES.glob("*.jsonl")):
        for inv in equiv.load(path):
            for key in inv.env:
                if key not in equiv.CONTROLLED_ENV_KEYS:
                    leaks.append(f"{path.name}:{inv.program}:{key}")
    assert not leaks, f"fixtures carry env outside the controlled base: {leaks}"


