def test_assertion1_the_ports_flags_are_all_declared():
    flags = equiv.declared_run_flags()
    for run in equiv.by_program(equiv.load(PORT), "run.py"):
        equiv.assert_flags_declared(run.argv, flags)


def test_assertion1_the_shells_skip_tensor_gate_is_gone():
    """The shell still passes --skip-tensor-gate (#264); run.py dropped it.

    This is why the harness records the shell as the *expected-broken* side,
    not as a target the port must match: had the port reproduced the shell's
    flag, assertion 1 would fail on the port too.
    """
    flags = equiv.declared_run_flags()
    shell_run = equiv.by_program(equiv.load(SHELL), "run.py")[0]
    with pytest.raises(AssertionError):
        equiv.assert_flags_declared(shell_run.argv, flags)


def test_assertion2_env_difference_matches_between_the_drivers():
    for fixture in (SHELL, PORT):
        equiv.assert_arm_env_delta(equiv.load(fixture), key=equiv.TENSOR_ENV)


def test_assertion2_ds4_server_only_not_run_py(tmp_path) -> None:
    """The run.py client is not asserted; a leftover on it fails nothing.

    The experiment's variable is the route the *server* takes, so the env delta
    is asserted on the server's child only. To prove the scope, give the run.py
    client a state that would fail assertion 2 if it were checked (a leftover
    "7" that is neither set:1 nor absent) and assert `assert_arm_env_delta`
    still passes -- the client is simply not the subject of #149, and the port
    must not be forced to strip the operator's export from its client env.
    """
    out = tmp_path / "rec.jsonl"
    shim = equiv.write_shim(tmp_path / "shim", out)
    equiv.run_fake(
        shim,
        "ds4-server",
        "r",
        [],
        {},
        (equiv.TENSOR_ENV,),
        out,
        tmp_path / "s.log",
        via="ds4-server",
    )
    equiv.run_fake(
        shim,
        "run.py",
        "r",
        [],
        {equiv.TENSOR_ENV: "7"},
        (),
        out,
        tmp_path / "s.log",
        via="run.py",
    )
    recs = equiv.load(out)
    equiv.assert_arm_env_delta(recs, key=equiv.TENSOR_ENV)  # only checks server
    run_env = equiv.by_program(recs, "run.py")[0].env
    assert equiv.env_key_state(run_env, equiv.TENSOR_ENV) == "set:7"


def test_assertion3_server_argv_is_identical_between_the_drivers():
    flags = equiv.declared_run_flags()
    for arm in ("t", "r"):
        shell_srv = equiv.by_program(equiv.load(SHELL), "ds4-server")
        port_srv = equiv.by_program(equiv.load(PORT), "ds4-server")
        s = next(x for x in shell_srv if x.arm == arm)
        p = next(x for x in port_srv if x.arm == arm)
        assert equiv.canonical(s.argv, flags) == equiv.canonical(p.argv, flags)


def test_assertion3_run_py_diff_is_exactly_the_sanctioned_fixes():
    flags = equiv.declared_run_flags()
    shell_run = equiv.by_program(equiv.load(SHELL), "run.py")[0].argv
    port_run = equiv.by_program(equiv.load(PORT), "run.py")[0].argv
    shell_only, port_only = equiv.argv_difference(shell_run, port_run, flags)
    assert shell_only == {("--skip-tensor-gate",)}  # #264, and only that
    # the port adds exactly the #264 fix and the --server-log (the shell
    # redirected stdout to a log instead of telling run.py where to write).
    assert port_only == {
        ("--allow-unverified-route",),
        ("--server-log", "out/server-t-sweep1.log"),
    }
    # both sides name the same backend, trials, client -- the measurement inputs
    for side in (shell_run, port_run):
        assert "--backend" in side and "--client" in side and "--trials" in side
