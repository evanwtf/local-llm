def route_consumer(tag: str, tmp_path: pathlib.Path) -> str | None:
    """route_ab_report's own window parser, fed one sweep line."""
    run_dir = tmp_path / "run"
    run_dir.mkdir(exist_ok=True)
    (run_dir / "sweep-order.txt").write_text(f"{tag} 08:00:00 08:10:00\n")
    # tz-aware is only to satisfy ruff: read_windows reads the anchor's .date()
    # and then builds naive windows, so awareness is irrelevant to the result.
    anchor = dt.datetime(2026, 9, 9, 8, tzinfo=dt.UTC)
    wins = route_ab_report.read_windows(run_dir, "t-sweep", "r-sweep", anchor)
    return wins[0][1] if wins else None


def test_the_driver_tag_roundtrips_through_its_report(tmp_path):
    equiv.assert_tag_roundtrips(TAG, "t", lambda t: route_consumer(t, tmp_path))


def test_the_bare_default_tag_is_unparseable(tmp_path):
    """Without tag_for the ab_driver default ships a tag nobody can read."""
    for bad in equiv.default_tags():
        assert route_consumer(bad, tmp_path) is None, bad


